/**
 * Scaffold Staging & Conflict-Free Promotion Manager (Section 5.3)
 *
 * Implements:
 * 1. Pre-flight directory analysis (tolerance matrix) -> CLEAN_BOOTSTRAP_ELIGIBLE vs CONFLICT_DETECTED
 * 2. Isolated staging in `.tmp-scaffold/` (or designated directory)
 * 3. Git hijack prevention: strips staged `.git` directory before promotion
 * 4. Safe atomic promotion preserving pre-existing files: SPEC.md, README.md, .git, .ai-manager, tasks/, etc.
 * 5. File permissions preservation (`0o755` for scripts) & Windows writable attribute sanity
 * 6. Symlink path traversal guards
 */

import * as fs from 'node:fs';
import * as path from 'node:path';

export const PROTECTED_FILENAMES = new Set<string>([
  'spec.md',
  'readme.md',
  '.git',
  '.ai-manager',
  '.gitignore',
  'license',
  'licence',
  'tasks',
]);

export interface DirectoryPreflightResult {
  readonly eligible: boolean;
  readonly reason: 'CLEAN_BOOTSTRAP_ELIGIBLE' | 'CONFLICT_DETECTED';
  readonly conflictingFiles: readonly string[];
}

export interface PromoteScaffoldOptions {
  readonly stagingDir: string;
  readonly workspaceRoot: string;
  readonly protectedFilenames?: readonly string[];
}

export interface PromoteScaffoldResult {
  readonly promotedFiles: readonly string[];
  readonly skippedFiles: readonly string[];
}

/**
 * Checks if a relative path or file name is protected from overwrite.
 */
export function isProtectedPath(relPath: string, customProtected?: readonly string[]): boolean {
  const norm = relPath.replace(/\\/g, '/').toLowerCase();
  const rootSegment = norm.split('/')[0];
  if (!rootSegment) return false;

  if (PROTECTED_FILENAMES.has(rootSegment)) {
    return true;
  }
  if (norm.startsWith('.env')) {
    return true;
  }
  if (norm.endsWith('.md')) {
    return true;
  }
  if (customProtected) {
    for (const p of customProtected) {
      if (rootSegment === p.toLowerCase()) return true;
    }
  }
  return false;
}

/**
 * Analyzes workspace root against tolerance matrix before scaffolding.
 */
export async function preflightWorkspaceDirectory(workspaceRoot: string): Promise<DirectoryPreflightResult> {
  let entries: string[];
  try {
    entries = await fs.promises.readdir(workspaceRoot);
  } catch {
    return { eligible: true, reason: 'CLEAN_BOOTSTRAP_ELIGIBLE', conflictingFiles: [] };
  }

  const conflicting: string[] = [];
  for (const entry of entries) {
    if (isProtectedPath(entry)) {
      continue;
    }
    // Any other file or non-staging folder is considered existing code/manifest
    conflicting.push(entry);
  }

  if (conflicting.length > 0) {
    return {
      eligible: false,
      reason: 'CONFLICT_DETECTED',
      conflictingFiles: conflicting.sort(),
    };
  }

  return {
    eligible: true,
    reason: 'CLEAN_BOOTSTRAP_ELIGIBLE',
    conflictingFiles: [],
  };
}

/**
 * Strips staged .git folder generated by scaffold CLI tools to prevent repository hijack.
 */
export async function stripStagedGit(stagingDir: string): Promise<boolean> {
  const stagedGitDir = path.join(stagingDir, '.git');
  try {
    await fs.promises.rm(stagedGitDir, { recursive: true, force: true });
    return true;
  } catch {
    return false;
  }
}

/**
 * Promotes files from staging directory to workspace root with symlink safety and permission retention.
 */
export async function promoteStagedFiles(options: PromoteScaffoldOptions): Promise<PromoteScaffoldResult> {
  const { stagingDir, workspaceRoot, protectedFilenames } = options;

  // 1. Purge staged .git if present
  await stripStagedGit(stagingDir);

  const promotedFiles: string[] = [];
  const skippedFiles: string[] = [];

  async function walkAndPromote(currentStaging: string, relPrefix = ''): Promise<void> {
    const entries = await fs.promises.readdir(currentStaging, { withFileTypes: true });

    for (const entry of entries) {
      const relPath = relPrefix ? `${relPrefix}/${entry.name}` : entry.name;
      const stagingItemPath = path.join(currentStaging, entry.name);
      const targetItemPath = path.join(workspaceRoot, relPath);

      // Symlink path traversal security verification
      if (entry.isSymbolicLink()) {
        try {
          const linkTarget = await fs.promises.readlink(stagingItemPath);
          const resolvedTarget = path.resolve(currentStaging, linkTarget);
          const resolvedRoot = path.resolve(stagingDir);
          // If the link points outside staging directory, reject/skip it
          if (!resolvedTarget.startsWith(resolvedRoot)) {
            skippedFiles.push(relPath);
            continue;
          }
        } catch {
          skippedFiles.push(relPath);
          continue;
        }
      }

      if (entry.isDirectory()) {
        // Do not traverse into protected root directories
        if (!relPrefix && isProtectedPath(entry.name, protectedFilenames)) {
          skippedFiles.push(relPath);
          continue;
        }
        await fs.promises.mkdir(targetItemPath, { recursive: true });
        await walkAndPromote(stagingItemPath, relPath);
      } else {
        // Protect pre-existing protected files in destination
        if (isProtectedPath(relPath, protectedFilenames)) {
          let destExists = false;
          try {
            await fs.promises.access(targetItemPath, fs.constants.F_OK);
            destExists = true;
          } catch {
            destExists = false;
          }

          if (destExists) {
            skippedFiles.push(relPath);
            continue;
          }
        }

        // Ensure parent destination directory exists
        await fs.promises.mkdir(path.dirname(targetItemPath), { recursive: true });

        // Copy with mode & timestamps
        const srcStat = await fs.promises.stat(stagingItemPath);
        await fs.promises.copyFile(stagingItemPath, targetItemPath);

        // Ensure file is writable on Windows and executable permissions (0o755) preserved on POSIX
        try {
          let mode = srcStat.mode;
          // If source had executable bit or is a wrapper script (.sh, gradlew, mvnw), preserve or set 0o755
          const isExec = (mode & 0o111) !== 0 || entry.name.endsWith('.sh') || entry.name === 'gradlew' || entry.name === 'mvnw';
          if (isExec) {
            mode = mode | 0o755;
          }
          // Make sure user write bit is present
          mode = mode | 0o200;
          await fs.promises.chmod(targetItemPath, mode);
        } catch {
          // Non-fatal on systems where chmod has restrictions
        }

        promotedFiles.push(relPath);
      }
    }
  }

  await walkAndPromote(stagingDir);

  return {
    promotedFiles: promotedFiles.sort(),
    skippedFiles: skippedFiles.sort(),
  };
}
